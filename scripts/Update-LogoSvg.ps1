# Writes Graphite/src/App/LogoSvg.h: Graphite.svg's bytes as an array, which the title bar
# parses to draw the application's mark.
#
# Run by hand after changing the SVG, and commit the header with it. The SVG stays the one
# source of the mark's shape; the header only carries it into the executable and the tests.
#
#   .\scripts\Update-LogoSvg.ps1          # rewrites the header
#   .\scripts\Update-LogoSvg.ps1 -Check   # exits non-zero when the header is out of date

[CmdletBinding()]
param(
    [string] $Root,
    [switch] $Check
)

$ErrorActionPreference = 'Stop'

# Not a default on the parameter: $PSScriptRoot is not yet populated while the param block is
# being bound, so a default computed there binds an empty string.
if (-not $Root)
{
    $Root = Split-Path -Parent $PSScriptRoot
}

$source = Join-Path $Root 'Graphite\resources\Graphite.svg'
$target = Join-Path $Root 'Graphite\src\App\LogoSvg.h'

# The file's bytes with every CRLF turned into LF: git converts line endings on checkout, and
# without this the same commit would write a different header in a checkout that converts.
$raw = [System.IO.File]::ReadAllBytes($source)
$bytes = New-Object System.Collections.Generic.List[byte]

for ($i = 0; $i -lt $raw.Length; $i++)
{
    if ($raw[$i] -eq 13 -and $i + 1 -lt $raw.Length -and $raw[$i + 1] -eq 10)
    {
        continue
    }

    $bytes.Add($raw[$i])
}

$bytes = $bytes.ToArray()

$lines = New-Object System.Collections.Generic.List[string]

for ($i = 0; $i -lt $bytes.Length; $i += 16)
{
    $end = [Math]::Min($i + 16, $bytes.Length)
    $row = for ($j = $i; $j -lt $end; $j++) { '0x{0:x2}' -f $bytes[$j] }
    $lines.Add("`t`t" + ($row -join ', ') + ',')
}

$header = @"
#pragma once

// Generated by scripts/Update-LogoSvg.ps1 from Graphite/resources/Graphite.svg. Do not edit:
// change the SVG and run the script again.

#include <cstddef>

namespace Graphite {

	inline constexpr unsigned char kLogoSvg[] = {
$($lines -join "`n")
	};

	inline constexpr std::size_t kLogoSvgSize = sizeof(kLogoSvg);
}

"@ -replace "`r`n", "`n"

if ($Check)
{
    # Compared without carriage returns, so a checkout that converts line endings still
    # matches the header the script would write.
    $current = if (Test-Path $target) { [System.IO.File]::ReadAllText($target) -replace "`r`n", "`n" } else { '' }

    if ($current -ne $header)
    {
        # Not Write-Error: with ErrorActionPreference at Stop it throws before the exit, and a
        # caller in the same session would see the exit code of whatever ran before.
        [Console]::Error.WriteLine("$target is out of date with $source. Run scripts\Update-LogoSvg.ps1.")
        exit 1
    }

    exit 0
}

[System.IO.File]::WriteAllText($target, $header, (New-Object System.Text.UTF8Encoding($false)))
Write-Host "Wrote $target ($($bytes.Length) bytes)."
