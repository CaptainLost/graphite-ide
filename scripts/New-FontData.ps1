<#
.SYNOPSIS
    Regenerates the compiled-in font data under Core/src/Core/ImGui/Fonts from vendor/fonts.

.DESCRIPTION
    Builds ImGui's own binary_to_compressed_c tool into a temporary directory, runs it over each
    font, and writes one .cpp per font. Run it after replacing a .ttf in vendor/fonts, then
    regenerate the project files with premake.
#>
$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
$vcvars = 'C:\Program Files\Microsoft Visual Studio\18\Community\VC\Auxiliary\Build\vcvars64.bat'
$toolSource = Join-Path $root 'vendor\imgui\misc\fonts\binary_to_compressed_c.cpp'
$outputDirectory = Join-Path $root 'Core\src\Core\ImGui\Fonts'

$fonts = @(
    @{ File = 'JetBrainsMono-Regular.ttf';       Name = 'JetBrainsMonoRegular' },
    @{ File = 'materialdesignicons-webfont.ttf'; Name = 'MaterialDesignIcons' },
    @{ File = 'Inter-Regular.ttf';               Name = 'InterRegular' },
    @{ File = 'Inter-SemiBold.ttf';              Name = 'InterSemiBold' }
)

$work = Join-Path ([IO.Path]::GetTempPath()) ('graphite-fontdata-' + [Guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $work | Out-Null

try {
    Copy-Item $toolSource $work
    $build = "call `"$vcvars`" >nul && cd /d `"$work`" && cl /nologo /O2 /EHsc binary_to_compressed_c.cpp >nul"
    cmd.exe /c $build
    $tool = Join-Path $work 'binary_to_compressed_c.exe'
    if (-not (Test-Path $tool)) { throw 'Could not build binary_to_compressed_c' }

    New-Item -ItemType Directory -Force $outputDirectory | Out-Null
    $utf8 = New-Object System.Text.UTF8Encoding($false)

    foreach ($font in $fonts) {
        $input = Join-Path $root ('vendor\fonts\' + $font.File)
        $name = $font.Name
        $lines = & $tool -nostatic $input $name
        if ($LASTEXITCODE -ne 0) { throw "binary_to_compressed_c failed on $($font.File)" }

        # The tool's banner names the absolute path it was run on; the data is all that matters.
        $data = ($lines | Where-Object { $_ -notmatch '^// ' }) -join "`r`n"

        $text = @"
// Generated by scripts/New-FontData.ps1 from vendor/fonts/$($font.File). Do not edit.
#include "corepch.h"

#include "Core/ImGui/EmbeddedFonts.h"

namespace Core {

	namespace {
$data
	}

	EmbeddedFont $name()
	{
		return { ${name}_compressed_data, static_cast<int>(${name}_compressed_size) };
	}
}

"@
        [IO.File]::WriteAllText((Join-Path $outputDirectory ($name + '.cpp')), $text, $utf8)
        Write-Host "Wrote $name.cpp"
    }
}
finally {
    Remove-Item -Recurse -Force $work
}
