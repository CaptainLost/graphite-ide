<#
.SYNOPSIS
    Regenerates vendor/fonts/IconsLucide.h from lucide-static's font/info.json.

.DESCRIPTION
    Writes one `#define ICON_LC_<NAME> "<utf8>"` per icon, the name upper-cased with each
    `-` turned into `_`, in ordinal order of the names. The header must come from the same
    lucide-static version as vendor/fonts/lucide.ttf, since a codepoint names a different
    icon from one version to the next. Run it after replacing the font, with the font's
    version; then run scripts/New-FontData.ps1 for the font itself.

.PARAMETER Version
    The lucide-static version whose info.json is read. Defaults to 0.460.0, written
    here by hand: the version vendor/fonts/lucide.ttf was taken from. Change the
    default whenever the font is replaced.

.PARAMETER InfoJson
    A local copy of that version's font/info.json. When omitted, it is downloaded from
    unpkg.

.EXAMPLE
    .\scripts\New-IconHeader.ps1
#>
[CmdletBinding()]
param(
    [string] $Version = '0.460.0',
    [string] $InfoJson
)

$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
$outputPath = Join-Path $root 'vendor\fonts\IconsLucide.h'
$source = "https://unpkg.com/lucide-static@$Version/font/info.json"

$work = $null
try {
    if (-not $InfoJson) {
        $work = Join-Path ([IO.Path]::GetTempPath()) ('graphite-iconheader-' + [Guid]::NewGuid().ToString('N'))
        New-Item -ItemType Directory -Path $work | Out-Null
        $InfoJson = Join-Path $work 'info.json'
        [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
        Invoke-WebRequest -Uri $source -OutFile $InfoJson -UseBasicParsing
    }

    $icons = [IO.File]::ReadAllText($InfoJson, [Text.Encoding]::UTF8) | ConvertFrom-Json

    # WARNING: sorted ordinally, because Sort-Object's culture-aware comparison ignores the
    # hyphens that separate the words of a name.
    $names = [string[]] @($icons.PSObject.Properties | ForEach-Object { $_.Name })
    [Array]::Sort($names, [StringComparer]::Ordinal)

    $lines = New-Object System.Collections.Generic.List[string]
    $lines.Add("// Generated by scripts/New-IconHeader.ps1 from lucide-static $Version's font/info.json. Do not edit.")
    $lines.Add("// For use with vendor/fonts/lucide.ttf from the same version.")
    $lines.Add('')
    $lines.Add('#pragma once')
    $lines.Add('')

    $defined = @{}
    foreach ($name in $names) {
        $encoded = $icons.$name.encodedCode
        if ($encoded -notmatch '^\\([0-9a-fA-F]+)$') { throw "Icon '$name' has an unexpected code '$encoded'" }
        $codepoint = [Convert]::ToInt32($Matches[1], 16)

        $constant = 'ICON_LC_' + $name.ToUpperInvariant().Replace('-', '_')
        if ($constant -notmatch '^ICON_LC_[A-Z0-9_]+$') { throw "Icon '$name' does not make a C identifier" }
        if ($defined.ContainsKey($constant)) { throw "Icons '$name' and '$($defined[$constant])' make the same constant" }
        $defined[$constant] = $name

        $bytes = [Text.Encoding]::UTF8.GetBytes([char]::ConvertFromUtf32($codepoint))
        $escaped = -join ($bytes | ForEach-Object { '\x{0:x2}' -f $_ })
        $lines.Add(('#define {0} "{1}"{2}// U+{3:X4}' -f $constant, $escaped, "`t", $codepoint))
    }

    $utf8 = New-Object System.Text.UTF8Encoding($false)
    [IO.File]::WriteAllText($outputPath, (($lines -join "`r`n") + "`r`n"), $utf8)
    Write-Host "Wrote IconsLucide.h with $($defined.Count) icons from lucide-static $Version"
}
finally {
    if ($work) { Remove-Item -Recurse -Force $work }
}
